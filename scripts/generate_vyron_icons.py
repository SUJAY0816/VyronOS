def main():
    print(f"Generating {len(SVGS)} Vyron geometric SVG icons into {ICONS_DIR}...")
    for name, svg_content in SVGS.items():
        svg_file = os.path.join(ICONS_DIR, f"{name}.svg")
        with open(svg_file, "w") as f:
            f.write(svg_content.strip())

    # Also generate PNG fallbacks for key sizes (16, 22, 24, 32, 48, 64)
    # Using Pillow to render clean icons
    for size in [16, 22, 24, 32, 48, 64]:
        size_dir = os.path.join(ICONS_DIR, f"{size}x{size}")
        os.makedirs(size_dir, exist_ok=True)
        for name in SVGS:
            img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
            draw = ImageDraw.Draw(img)
            pad = max(2, size // 8)
            # Draw distinctive geometric boundary
            draw.rounded_rectangle([(pad, pad), (size - pad, size - pad)], radius=size//6, fill=(26, 30, 38, 230), outline=(124, 140, 255, 255), width=max(1, size//24))
            
            # Simple geometric emblem inside
            cx, cy = size // 2, size // 2
            r = size // 4
            draw.polygon([(cx - r, cy - r), (cx, cy + r), (cx + r, cy - r)], fill=(124, 140, 255, 255))
            
            png_path = os.path.join(size_dir, f"{name}.png")
            img.save(png_path, "PNG")

    print(f"Successfully generated 22 SVG icons and {len(SVGS) * 6} PNG icons (16x16, 22x22, 24x24, 32x32, 48x48, 64x64).")

if __name__ == "__main__":
    main()
